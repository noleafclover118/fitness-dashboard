/**
 * Writes out/sw.js: a service worker that pre-caches the whole built app so it
 * opens and works with no signal (e.g. at the gym). Runs after `next build`.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'out');
const base = process.env.NEXT_PUBLIC_BASE_PATH ?? '';

const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (!e.name.endsWith('.map')) files.push(p);
  }
})(out);

const hash = crypto.createHash('sha256');
const urls = [];
for (const f of files.sort()) {
  const rel = path.relative(out, f).split(path.sep).join('/');
  if (rel === 'sw.js' || rel === '404.html' || rel.startsWith('_not-found')) continue;
  hash.update(rel).update(fs.readFileSync(f));
  urls.push(`${base}/${rel.replace(/(^|\/)index\.html$/, '$1')}`);
}
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs — do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = 'fitness-' + VERSION;
const BASE = ${JSON.stringify(base)};
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('fitness-') && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // Pages ignore the query string (/workout/?id=3 is the same file as /workout/).
    const hit = await cache.match(req, { ignoreSearch: req.mode === 'navigate' || url.pathname.endsWith('.txt') });
    if (hit) return hit;
    try {
      const res = await fetch(req);
      if (res.ok && url.pathname.startsWith(BASE + '/_next/')) cache.put(req, res.clone());
      return res;
    } catch (e) {
      if (req.mode === 'navigate') return (await cache.match(BASE + '/')) || Response.error();
      throw e;
    }
  })());
});
`;
fs.writeFileSync(path.join(out, 'sw.js'), sw);
console.log(`Service worker: ${urls.length} files pre-cached (version ${version})`);
